import asyncio
from contextlib import asynccontextmanager

from fastapi import FastAPI

from app.core.config import get_settings
from app.core.errors import register_error_handlers
from app.core import scheduler
from app.routers import alarm, appointments, auth, calls, device_health, emergency_contact, escalation, geofence, health, kyc, linkage, location, medication, messages, notifications, panic, permissions, records, wellness
from app.services import appointments_service, call_service, device_health_service, escalation_service, external_contact_service, medication_service, notification_service, wellness_service

settings = get_settings()

# Background jobs (Task 2.3). Each runs every SCHEDULER_TICK_S seconds; see app/core/scheduler.py.
scheduler.register("device_offline_sweep", device_health_service.sweep_offline)
scheduler.register("medication_missed_sweep", medication_service.sweep_missed)  # Task 3.3 (before the dispatch, so alerts go out the same minute)
scheduler.register("wellness_sweep", wellness_service.sweep)  # Task 3.4 (before the dispatch)
scheduler.register("escalation_sweep", escalation_service.sweep)  # Task 3.5 (after the other sweeps, before the dispatch)
scheduler.register("external_contact_sweep", external_contact_service.sweep)  # Task 3.8 (after the escalation sweep)
scheduler.register("call_sweep", call_service.sweep)  # Task 4.4
scheduler.register("appointment_tick", appointments_service.tick)  # Task 5.1 (reminders; after the sweeps, the dispatch only handles alert events)
scheduler.register("notification_dispatch", notification_service.dispatch_events)  # Task 3.1 (after the sweep)
scheduler.register("medication_tick", medication_service.tick)  # Task 3.2
scheduler.register("wellness_tick", wellness_service.tick)  # Task 3.4


@asynccontextmanager
async def lifespan(_: FastAPI):
    task = asyncio.create_task(scheduler.loop()) if settings.SCHEDULER_ENABLED else None
    try:
        yield
    finally:
        if task:
            task.cancel()


app = FastAPI(
    title=settings.APP_NAME,
    description="Bi-directional remote intervention and care coordination system.",
    version="0.1.0",
    lifespan=lifespan,
)

# Every error, from every endpoint, uses the SDS 11.2 error envelope.
register_error_handlers(app)

