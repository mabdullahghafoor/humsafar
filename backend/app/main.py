from fastapi import FastAPI

from app.core.config import get_settings
from app.core.errors import register_error_handlers
from app.routers import auth, health, kyc, linkage, location, permissions

settings = get_settings()

app = FastAPI(
    title=settings.APP_NAME,
    description="Bi-directional remote intervention and care coordination system.",
    version="0.1.0",
)

# Every error, from every endpoint, uses the SDS 11.2 error envelope.
register_error_handlers(app)

# --- Routers ---
# One router per SDS §8 service module, registered here as each is built.
app.include_router(health.router)
app.include_router(auth.router)  # Task 1.3
app.include_router(kyc.dependents_router)  # Task 1.4
app.include_router(kyc.guardians_router)  # Task 1.4
app.include_router(linkage.dependents_router)  # Task 1.5
app.include_router(linkage.guardians_router)  # Task 1.5
app.include_router(linkage.invitations_router)  # Task 1.5
app.include_router(permissions.router)  # Task 1.6
app.include_router(location.router)  # Task 2.1

